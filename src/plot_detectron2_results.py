#!/usr/bin/env python3
"""
Plot object-level Detectron2 results.

The input CSV is the object-level result file generated by
src.detectron2_inference. Multiple rows may belong to the same video frame.
"""

from __future__ import annotations

import argparse
import os

import matplotlib.pyplot as plt
import pandas as pd


def main():

    parser = argparse.ArgumentParser(
        description="Plot Detectron2 object-level results."
    )

    parser.add_argument(
        "--csv",
        required=True,
        help="Detectron2 object-level result CSV.",
    )

    parser.add_argument(
        "--out-dir",
        required=True,
        help="Output directory for plots.",
    )

    args = parser.parse_args()

    os.makedirs(
        args.out_dir,
        exist_ok=True,
    )

    df = pd.read_csv(args.csv)

    if df.empty:
        print(
            "Detectron2 result CSV contains no detections. "
            "No object-level plots were created."
        )
        return

    required_columns = {
        "frame",
        "score",
    }

    missing = (
        required_columns
        - set(df.columns)
    )

    if missing:
        raise KeyError(
            f"Missing required columns: "
            f"{sorted(missing)}"
        )

    # -------------------------------------------------------------------------
    # Detection confidence
    # -------------------------------------------------------------------------

    plt.figure(
        figsize=(10, 5)
    )

    plt.plot(
        df["frame"],
        df["score"],
        ".",
        markersize=2,
    )

    plt.xlabel("Frame")
    plt.ylabel("Detection score")

    plt.title(
        "Detectron2 detection confidence"
    )

    plt.grid(True)

    plt.tight_layout()

    plt.savefig(
        os.path.join(
            args.out_dir,
            "detectron2_scores.png",
        ),
        dpi=300,
    )

    plt.close()

    # -------------------------------------------------------------------------
    # Per-frame computation time
    #
    # The same computation time is repeated when a frame contains multiple
    # detections. Therefore one value per frame is used.
    # -------------------------------------------------------------------------

    if "compute_time_s" in df.columns:

        runtime_df = (
            df[
                [
                    "frame",
                    "compute_time_s",
                ]
            ]
            .drop_duplicates(
                subset=["frame"]
            )
            .sort_values("frame")
        )

        plt.figure(
            figsize=(10, 5)
        )

        plt.plot(
            runtime_df["frame"],
            runtime_df["compute_time_s"],
            linewidth=0.8,
        )

        plt.xlabel("Frame")
        plt.ylabel("Inference time [s]")

        plt.title(
            "Detectron2 inference time"
        )

        plt.grid(True)

        plt.tight_layout()

        plt.savefig(
            os.path.join(
                args.out_dir,
                "detectron2_inference_time.png",
            ),
            dpi=300,
        )

        plt.close()

    print(
        f"Plots saved: {args.out_dir}"
    )


if __name__ == "__main__":
    main()