@dataclass(frozen=True, slots=True)
class Candidate:
    """Normalized candidate row from either supported CSV schema."""
    source_row: int
    source_rank: int
    rank_for_video: int
    video_id: str
    video_path: Optional[Path]
    imu_measurement_id: str
    imu_path: Path
    label: str
    score: Optional[float]
    raw: Mapping[str, str] = field(default_factory=dict, repr=False)
    @property
    def stable_id(self) -> str:
        """Return a deterministic identifier independent of CSV row order."""
        material = "|".join(
            (
                self.video_id,
                str(self.video_path or ""),
                self.imu_measurement_id,
                str(self.imu_path),
            )
        )
        digest = hashlib.sha256(material.encode("utf-8")).hexdigest()[:12]
        return f"r{self.rank_for_video:04d}-{digest}"
    @property
    def safe_label(self) -> str:
        """Return a filesystem-safe compact candidate label."""
        value = re.sub(r"[^A-Za-z0-9._-]+", "_", self.label.strip())
        value = value.strip("._-") or self.imu_measurement_id or "candidate"
        return value[:80]
    def to_dict(self) -> dict[str, Any]:
        return {
            "source_row": self.source_row,
            "source_rank": self.source_rank,
            "rank_for_video": self.rank_for_video,
            "video_id": self.video_id,
            "video_path": str(self.video_path) if self.video_path else None,
            "imu_measurement_id": self.imu_measurement_id,
            "imu_path": str(self.imu_path),
            "label": self.label,
            "score": self.score,
            "stable_id": self.stable_id,
        }
