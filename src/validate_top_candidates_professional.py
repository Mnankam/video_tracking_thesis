def progress_message(index: int, total: int, candidate: Candidate, status: str) -> str:
    width = 28
    completed = min(width, int(width * index / max(total, 1)))
    bar = "#" * completed + "-" * (width - completed)
    return (
        f"[{bar}] {index:>3}/{total:<3} {status:<9} "
        f"rank={candidate.rank_for_video:<3} {candidate.label}"
    )
def emit_progress(config: Stage3Config, index: int, total: int, candidate: Candidate, status: str) -> None:
    if config.progress:
        print(progress_message(index, total, candidate, status), file=sys.stderr, flush=True)
def run_batch(config: Stage3Config, compatibility: CompatibilityReport) -> BatchSummary:
    """Run, resume, rank and export the selected top candidates."""
    started_clock = perf_counter()
    started_utc = utc_now()
    all_candidates = load_candidates(config)
    selected = select_candidates(config, all_candidates)
    validate_candidate_inputs(config, selected)
    ValidationConfig, ValidationResult, validate_video_vs_imu = import_stage2_api()
    state = load_resume_state(config.output_dir)
    successes: list[CandidateSuccess] = []
    failures: list[CandidateFailure] = []
    for index, candidate in enumerate(selected, start=1):
        run_directory = candidate_run_directory(config.output_dir, candidate)
        result_file = run_directory / "validation_result.json"
        previous = state.get("candidates", {}).get(candidate.stable_id, {})
        previous_status = previous.get("status") if isinstance(previous, Mapping) else None
        if config.resume and result_file.is_file():
            try:
                success = load_completed_candidate(candidate, run_directory)
                successes.append(success)
                update_resume_state(
                    config.output_dir, state, candidate, "success", run_directory,
                    {"resumed": True, "validation_result": str(result_file)},
                )
                emit_progress(config, index, len(selected), candidate, "resumed")
                LOGGER.info("Resumed candidate %s from %s", candidate.label, result_file)
                continue
            except Exception as exc:
                LOGGER.warning("Existing result for %s is unusable: %s", candidate.label, exc)
        if (
            config.resume
            and config.skip_failed_on_resume
            and previous_status == "failure"
            and (run_directory / "failure.json").is_file()
        ):
            failure_data = read_json(run_directory / "failure.json")
            failure = CandidateFailure(
                candidate=candidate,
                run_directory=run_directory,
                error_type=str(failure_data.get("error_type", "PreviousFailure")),
                error_message=str(failure_data.get("error_message", "previous failure")),
                traceback_file=Path(str(failure_data.get("traceback_file", run_directory / "failure_traceback.txt"))),
                timestamp_utc=str(failure_data.get("timestamp_utc", utc_now())),
                resumed=True,
            )
            failures.append(failure)
            emit_progress(config, index, len(selected), candidate, "skipped")
            continue
        try:
            emit_progress(config, index - 1, len(selected), candidate, "running")
            update_resume_state(config.output_dir, state, candidate, "running", run_directory)
            success = run_candidate(
                config,
                candidate,
                run_directory,
                ValidationConfig,
                ValidationResult,
                validate_video_vs_imu,
            )
            successes.append(success)
            update_resume_state(
                config.output_dir,
                state,
                candidate,
                "success",
                run_directory,
                {"validation_result": str(success.result_json), "runtime_s": success.runtime_s},
            )
            emit_progress(config, index, len(selected), candidate, "success")
        except KeyboardInterrupt:
            update_resume_state(config.output_dir, state, candidate, "interrupted", run_directory)
            raise
        except Exception as exc:
            LOGGER.exception("Candidate rank=%s failed", candidate.rank_for_video)
            failure = record_failure(candidate, run_directory, exc)
            failures.append(failure)
            update_resume_state(
                config.output_dir,
                state,
                candidate,
                "failure",
                run_directory,
                failure.csv_row(),
            )
            emit_progress(config, index, len(selected), candidate, "failure")
            if not config.continue_on_error:
                break
    ranked = rank_successes(config, successes)
    summary = BatchSummary(
        config=config,
        compatibility=compatibility,
        selected_candidates=selected,
        successes=ranked,
        failures=failures,
        started_utc=started_utc,
        finished_utc=utc_now(),
        runtime_s=perf_counter() - started_clock,
    )
    write_aggregate_outputs(summary)
    return summary
