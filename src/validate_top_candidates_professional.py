def find_report_html(result_data: Mapping[str, Any], run_directory: Path) -> Optional[Path]:
    artefacts = result_data.get("report_artifacts", {})
    candidates: list[Path] = []
    if isinstance(artefacts, Mapping):
        for key in ("html_path", "report_html", "html"):
            value = artefacts.get(key)
            if value:
                candidates.append(Path(str(value)))
    candidates.extend(
        (
            run_directory / "report" / "report.html",
            run_directory / "report.html",
        )
    )
    return next((path.resolve() for path in candidates if path.is_file()), None)
def success_from_result_data(
    candidate: Candidate,
    run_directory: Path,
    data: Mapping[str, Any],
    resumed: bool,
) -> CandidateSuccess:
    """Reconstruct a typed aggregate result from Stage-2 JSON."""
    metrics = data.get("metrics", {})
    synchronization = data.get("synchronization", {})
    if not isinstance(metrics, Mapping) or not isinstance(synchronization, Mapping):
        raise ResumeStateError(
            f"Existing result has invalid metrics/synchronization: {run_directory}"
        )
    result_json = run_directory / "validation_result.json"
    return CandidateSuccess(
        candidate=candidate,
        metrics=dict(metrics),
        synchronization=dict(synchronization),
        video_summary=dict(data.get("video_summary", {})),
        imu_summary=dict(data.get("imu_summary", {})),
        runtime_s=float(data.get("runtime_s") or 0.0),
        run_directory=run_directory,
        result_json=result_json,
        report_html=find_report_html(data, run_directory),
        resumed=resumed,
    )
def load_completed_candidate(candidate: Candidate, run_directory: Path) -> CandidateSuccess:
    path = run_directory / "validation_result.json"
    if not path.is_file():
        raise ResumeStateError(f"Missing validation result: {path}")
    data = read_json(path)
    if not isinstance(data, Mapping):
        raise ResumeStateError(f"Validation result is not a JSON object: {path}")
    return success_from_result_data(candidate, run_directory, data, resumed=True)
