def run_candidate(
    config: Stage3Config,
    candidate: Candidate,
    run_directory: Path,
    ValidationConfig: type[Any],
    ValidationResult: type[Any],
    validate_video_vs_imu: Any,
) -> CandidateSuccess:
    """Execute one candidate through the unmodified Stage-2 pipeline."""
    run_directory.mkdir(parents=True, exist_ok=True)
    validation_config = make_validation_config(
        config, candidate, run_directory, ValidationConfig
    )
    write_json(run_directory / "stage3_candidate.json", candidate.to_dict())
    LOGGER.info("Starting candidate rank=%s label=%s", candidate.rank_for_video, candidate.label)
    result = validate_video_vs_imu(validation_config)
    if not isinstance(result, ValidationResult):
        raise TypeError(
            "validate_video_vs_imu() returned "
            f"{type(result).__name__}, expected ValidationResult."
        )
    result_data = result.as_dict() if hasattr(result, "as_dict") else dataclasses.asdict(result)
    result_json = run_directory / "validation_result.json"
    if not result_json.is_file():
        write_json(result_json, result_data)
    return success_from_result_data(candidate, run_directory, result_data, resumed=False)
def record_failure(candidate: Candidate, run_directory: Path, exc: BaseException) -> CandidateFailure:
    """Persist a full traceback while keeping CSV/HTML messages compact."""
    run_directory.mkdir(parents=True, exist_ok=True)
    trace_path = run_directory / "failure_traceback.txt"
    trace_text = "".join(traceback.format_exception(type(exc), exc, exc.__traceback__))
    trace_path.write_text(trace_text, encoding="utf-8", newline="\n")
    failure = CandidateFailure(
        candidate=candidate,
        run_directory=run_directory,
        error_type=type(exc).__name__,
        error_message=str(exc),
        traceback_file=trace_path,
        timestamp_utc=utc_now(),
    )
    write_json(run_directory / "failure.json", failure.csv_row())
    return failure
