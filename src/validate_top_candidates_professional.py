#!/usr/bin/env python3
"""
validate_top_candidates_professional.py
=======================================
Repository-specific Stage-3 batch validation for the master-thesis project
``video_tracking_thesis``.
Purpose
-------
The repository already contains two preceding workflow stages:
* ``src/find_best_validation_dataset.py`` computes a coarse pre-ranking of
  candidate IMU measurements for each tracked video. Its CSV output uses the
  columns ``video_id``, ``imu_path`` and ``rank_for_video``.
* ``src/validate_video_vs_imu_v2.py`` performs the detailed validation of one
  video signal against one IMU signal through ``ValidationConfig``,
  ``ValidationResult`` and ``validate_video_vs_imu()``.
This Stage-3 program connects both stages without duplicating their signal
processing. It reads the pre-ranked candidates, selects one video, validates
its best candidates with the Stage-2 pipeline, resumes interrupted runs, and
writes a reproducible aggregate comparison.
Repository integration
----------------------
The program intentionally imports and uses the real repository modules:
* ``validate_video_vs_imu_v2.py``
* ``validation/video_loader.py``
* ``validation/imu_loader.py``
* ``validation/preprocessing.py``
* ``validation/synchronization.py``
* ``validation/metrics.py``
* ``validation/plotting.py``
* ``validation/report.py``
The last seven modules are imported explicitly during the compatibility check.
Their actual execution is delegated to ``validate_video_vs_imu()`` so that this
batch wrapper does not fork the scientific implementation.
Supported candidate schemas
---------------------------
Primary repository schema, generated by ``find_best_validation_dataset.py``::
    video_id,video_path,imu_measurement_id,imu_path,...,score,rank_for_video
Legacy schema, used by the earlier ``validate_top_candidates.py``::
    rank,imu_csv,label
Both ``imu_path`` and ``imu_csv`` are accepted. If both exist, ``imu_path``
has precedence. ``rank_for_video`` has precedence over ``rank``.
Outputs
-------
The selected output directory receives:
* one subdirectory per candidate, containing the normal Stage-2 artefacts;
* ``comparison.csv`` with successful runs in final ranking order;
* ``failures.csv`` with isolated candidate errors;
* ``summary.json`` with configuration, compatibility and complete results;
* ``summary.html`` with a browsable professional comparison;
* ``stage3.log`` with detailed run diagnostics;
* ``resume_state.json`` with durable per-candidate status information.
Resume semantics
----------------
With ``--resume``, completed candidates are not recomputed. Their existing
``validation_result.json`` is loaded and included in the new aggregate files.
Failed candidates are retried by default. Use ``--skip-failed-on-resume`` to
keep previous failures skipped.
Exit codes
----------
0
    All selected candidates completed successfully.
1
    At least one selected candidate failed, but aggregate files were written.
2
    Configuration, input or repository compatibility error.
130
    Interrupted by the user.
"""
