def sortable_metric(value: Any, direction: str) -> float:
    number = parse_optional_float(value)
    if number is None:
        return float("inf")
    return -number if direction == "descending" else number
def rank_successes(config: Stage3Config, successes: Sequence[CandidateSuccess]) -> list[CandidateSuccess]:
    ranked = list(successes)
    ranked.sort(
        key=lambda item: (
            sortable_metric(metric_value(item.metrics, config.ranking_metric), config.ranking_direction),
            sortable_metric(metric_value(item.metrics, config.secondary_metric), config.secondary_direction),
            item.candidate.rank_for_video,
        )
    )
    for index, item in enumerate(ranked, start=1):
        item.final_rank = index
    return ranked
def write_csv(path: Path, rows: Sequence[Mapping[str, Any]], columns: Sequence[str]) -> Path:
    """Always write a header, even when there are no rows."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(columns), extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({key: jsonable(row.get(key)) for key in columns})
    temporary.replace(path)
    return path
def relative_link(target: Optional[Path], origin_directory: Path) -> str:
    if target is None:
        return ""
    try:
        return os.path.relpath(target, origin_directory).replace(os.sep, "/")
    except ValueError:
        return target.as_uri()
