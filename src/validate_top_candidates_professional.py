def utc_now() -> str:
    """Return an ISO-8601 UTC timestamp with second precision."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")
def jsonable(value: Any) -> Any:
    """Convert dataclasses, paths and non-finite floats to strict JSON values."""
    if value is None or isinstance(value, (str, bool, int)):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, datetime):
        return value.isoformat()
    if dataclasses.is_dataclass(value):
        return jsonable(dataclasses.asdict(value))
    if isinstance(value, Mapping):
        return {str(key): jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [jsonable(item) for item in value]
    if hasattr(value, "item"):
        try:
            return jsonable(value.item())
        except Exception:
            pass
    if hasattr(value, "as_dict"):
        try:
            return jsonable(value.as_dict())
        except Exception:
            pass
    return str(value)
def write_json(path: Path, value: Any) -> Path:
    """Atomically write strict UTF-8 JSON."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(jsonable(value), handle, ensure_ascii=False, indent=2, allow_nan=False)
        handle.write("\n")
    temporary.replace(path)
    return path
def read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)
def parse_optional_float(value: Any) -> Optional[float]:
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    try:
        number = float(text.replace(",", "."))
    except ValueError:
        return None
    return number if math.isfinite(number) else None
def parse_optional_int(value: Any) -> Optional[int]:
    number = parse_optional_float(value)
    return int(number) if number is not None else None
def first_non_empty(*values: Any) -> Optional[str]:
    for value in values:
        if value is not None and str(value).strip():
            return str(value).strip()
    return None
def first_non_null(*values: Any) -> Any:
    for value in values:
        if value is not None:
            return value
    return None
def metric_value(mapping: Mapping[str, Any], name: str) -> Any:
    """Read a metric while tolerating one level of nested dictionaries."""
    if name in mapping:
        return mapping[name]
    for value in mapping.values():
        if isinstance(value, Mapping) and name in value:
            return value[name]
    return None
def canonical_path(value: str, base_directory: Path) -> Path:
    """Resolve absolute or candidate-CSV-relative paths."""
    path = Path(os.path.expandvars(value)).expanduser()
    if not path.is_absolute():
        path = base_directory / path
    return path.resolve()
def normalize_identifier(value: str) -> str:
    """Normalize identifiers for case-insensitive video filtering."""
    return re.sub(r"[^a-z0-9]+", "", value.lower())
def infer_video_id(path: Optional[Path]) -> str:
    if path is None:
        return ""
    stem = path.stem
    for suffix in (
        "_results_inner_pipe_track_timeseries",
        "_inner_pipe_track_timeseries",
        "_timeseries",
        "_results",
    ):
        if stem.lower().endswith(suffix.lower()):
            return stem[: -len(suffix)]
    return stem
def infer_measurement_id(path: Path) -> str:
    if path.name.lower() == "data.csv" and path.parent.name:
        return path.parent.name
    return path.stem
def format_number(value: Any, digits: int = 6) -> str:
    if value is None or value == "":
        return ""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    if not math.isfinite(number):
        return ""
    return f"{number:.{digits}g}"
def setup_logging(output_dir: Path, level: str) -> Path:
    """Configure console and persistent logging without duplicate handlers."""
    output_dir.mkdir(parents=True, exist_ok=True)
    log_file = output_dir / "stage3.log"
    root = logging.getLogger()
    root.handlers.clear()
    root.setLevel(getattr(logging, level.upper()))
    formatter = logging.Formatter(
        "%(asctime)s | %(levelname)-8s | %(name)s | %(message)s"
    )
    console = logging.StreamHandler(sys.stderr)
    console.setFormatter(formatter)
    file_handler = logging.FileHandler(log_file, encoding="utf-8")
    file_handler.setFormatter(formatter)
    root.addHandler(console)
    root.addHandler(file_handler)
    return log_file
