        self.candidates_csv = self.candidates_csv.expanduser().resolve()
        self.output_dir = self.output_dir.expanduser().resolve()
        if self.video_csv is not None:
            self.video_csv = self.video_csv.expanduser().resolve()
        if self.top_k < 1:
            raise ConfigurationError("--top-k must be at least 1.")
        if self.smoothing_window < 1:
            raise ConfigurationError("--smoothing-window must be at least 1.")
