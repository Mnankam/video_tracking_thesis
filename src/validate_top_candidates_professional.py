def print_final_summary(summary: BatchSummary) -> None:
    print("=" * 88)
    print("STAGE 3 FINAL RANKING")
    print("=" * 88)
    if not summary.successes:
        print("No candidate completed successfully.")
    for item in summary.successes:
        row = item.comparison_row()
        print(
            f"{item.final_rank:>2}. source={item.candidate.rank_for_video:<3} "
            f"{item.candidate.label:<28.28} "
            f"Pearson={format_number(row['pearson_correlation'], 5):>9} "
            f"RMSE={format_number(row['rmse'], 5):>9} "
            f"Lag={format_number(row['estimated_lag_s'], 5):>9}"
        )
    print("-" * 88)
    print(f"Successful: {len(summary.successes)} | Failed: {len(summary.failures)}")
    print(f"comparison.csv: {summary.config.output_dir / 'comparison.csv'}")
    print(f"summary.html:   {summary.config.output_dir / 'summary.html'}")
    if summary.best:
        print(f"Best candidate: {summary.best.candidate.label}")
def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        config = config_from_args(args)
        config.output_dir.mkdir(parents=True, exist_ok=True)
        setup_logging(config.output_dir, config.log_level)
        script_path = Path(__file__).resolve()
        repository_root = discover_repository_root(script_path)
        compatibility = check_repository_compatibility(repository_root)
        write_json(config.output_dir / "repository_compatibility.json", compatibility.to_dict())
        if not compatibility.compatible:
            failed = [item for item in compatibility.checks if not item["ok"]]
            raise RepositoryCompatibilityError(
                "Repository compatibility check failed:\n"
                + "\n".join(f"- {item['check']}: {item['detail']}" for item in failed)
            )
        LOGGER.info("Repository compatibility verified: %s", repository_root)
        if args.check_only:
            print(json.dumps(jsonable(compatibility.to_dict()), ensure_ascii=False, indent=2))
            return 0
        summary = run_batch(config, compatibility)
        print_final_summary(summary)
        return 1 if summary.failures else 0
    except KeyboardInterrupt:
        LOGGER.error("Stage-3 validation interrupted by user.")
        return 130
    except (Stage3Error, FileNotFoundError, ValueError) as exc:
        LOGGER.error("%s", exc)
        return 2
    except Exception as exc:
        LOGGER.exception("Unexpected Stage-3 failure: %s", exc)
        return 2
if __name__ == "__main__":
    raise SystemExit(main())
