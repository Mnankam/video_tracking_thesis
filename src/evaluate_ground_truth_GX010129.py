# =============================================================================
# Main
# =============================================================================

def main() -> None:
    """Program entry point."""

    validate_directories()
    ensure_output_directory()

    all_rows: list[dict[str, Any]] = []

    for class_name, config in CLASS_CONFIG.items():
        class_rows = evaluate_class(
            class_name,
            config,
        )

        all_rows.extend(class_rows)

    if not all_rows:
        raise RuntimeError(
            "No evaluation rows were generated."
        )

    per_frame = pd.DataFrame(
        all_rows
    )

    per_frame = per_frame.sort_values(
        [
            "class",
            "frame",
        ]
    ).reset_index(
        drop=True
    )

    per_frame.to_csv(
        PER_FRAME_CSV,
        index=False,
    )

    summary = summarize_metrics(
        per_frame
    )

    summary.to_csv(
        SUMMARY_CSV,
        index=False,
    )

    create_plots(
        per_frame
    )

    save_text_summary(
        summary
    )

    print_summary(
        summary
    )


if __name__ == "__main__":
    main()