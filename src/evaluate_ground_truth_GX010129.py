# Per-class evaluation
# =============================================================================

def evaluate_class(
    class_name: str,
    config: dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Evaluate one semantic class for all available GT masks.
    """

    gt_dir = Path(config["gt_dir"])
    prediction_dir = Path(
        config["prediction_dir"]
    )

    gt_suffix = str(
        config["gt_suffix"]
    )

    prediction_suffix = str(
        config["prediction_suffix"]
    )

    gt_files = sorted(
        gt_dir.glob(
            f"*{gt_suffix}"
        )
    )

    if not gt_files:
        raise FileNotFoundError(
            f"No GT masks found for {class_name} in:\n"
            f"{gt_dir}"
        )

    print()
    print("=" * 80)
    print(
        f"Evaluating class: {class_name}"
    )
    print("=" * 80)

    rows: list[dict[str, Any]] = []

    for index, gt_path in enumerate(
        gt_files,
        start=1,
    ):
        frame_name = extract_frame_name(
            gt_path,
            gt_suffix,
        )

        frame_number = frame_number_from_name(
            frame_name
        )

        prediction_path = (
            prediction_dir
            / f"{frame_name}{prediction_suffix}"
        )

        if not prediction_path.is_file():
            print(
                f"[WARNING] Missing prediction: "
                f"{prediction_path.name}"
            )

            rows.append(
                {
                    "frame": frame_number,
                    "frame_name": frame_name,
                    "class": class_name,
                    "status": "missing_prediction",
                    "iou": np.nan,
                    "dice": np.nan,
                    "gt_pixels": np.nan,
                    "prediction_pixels": np.nan,
                    "intersection_pixels": np.nan,
                    "union_pixels": np.nan,
                    "prediction_gt_ratio": np.nan,
                    "gt_coverage": np.nan,
                }
            )

            continue

        gt_mask = load_binary_mask(
            gt_path
        )

        prediction_mask = load_binary_mask(
            prediction_path
        )

        if gt_mask.shape != prediction_mask.shape:
            gt_h, gt_w = gt_mask.shape[:2]
            pred_h, pred_w = prediction_mask.shape[:2]

            gt_aspect = gt_w / gt_h
            pred_aspect = pred_w / pred_h

            if not np.isclose(
                gt_aspect,
                pred_aspect,
                rtol=1e-3,
            ):
                raise ValueError(
                    f"Mask aspect-ratio mismatch for "
                    f"{frame_name} / {class_name}: "
                    f"GT={gt_mask.shape}, "
                    f"Prediction={prediction_mask.shape}"
                )

            print(
                f"Resizing prediction mask for "
                f"{frame_name} / {class_name}: "
                f"{pred_w}x{pred_h} -> "
                f"{gt_w}x{gt_h}"
            )

            prediction_mask = cv2.resize(
                prediction_mask,
                (gt_w, gt_h),
                interpolation=cv2.INTER_NEAREST,
            )

            prediction_mask = np.where(
                prediction_mask > 0,
                255,
                0,
            ).astype(np.uint8)

        pixel_stats = compute_pixel_statistics(
            gt_mask,
            prediction_mask,
        )

        iou = compute_iou(
            gt_mask,
            prediction_mask,
        )

        dice = compute_dice(
            gt_mask,
            prediction_mask,
        )

        overlay_path = (
            OVERLAY_DIR
            / class_name
            / f"{frame_name}_overlay.png"
        )

        save_segmentation_overlay(
            gt_mask=gt_mask,
            prediction_mask=prediction_mask,
            output_path=overlay_path,
        )

        row = {
            "frame": frame_number,
            "frame_name": frame_name,
            "class": class_name,
            "status": "ok",
            "iou": float(iou),
            "dice": float(dice),
            **pixel_stats,
        }

        rows.append(row)

        print(
            f"[{index:02d}/{len(gt_files):02d}] "
            f"{frame_name} | "
            f"IoU={iou:.6f} | "
            f"Dice={dice:.6f} | "
            f"GT={pixel_stats['gt_pixels']} px | "
            f"Pred={pixel_stats['prediction_pixels']} px | "
            f"Ratio={pixel_stats['prediction_gt_ratio']:.4f} | "
            f"Coverage={pixel_stats['gt_coverage']:.4f}"
        )

    return rows


# =============================================================================
# Summary calculation
# =============================================================================

def summarize_metrics(
    frame: pd.DataFrame,
) -> pd.DataFrame:
    """
    Calculate descriptive statistics per semantic class.
    """

    successful = frame.loc[
        frame["status"] == "ok"
    ].copy()

    if successful.empty:
        raise RuntimeError(
            "No successful segmentation comparisons "
            "are available."
        )

    rows: list[dict[str, Any]] = []

    for class_name in sorted(
        successful["class"].unique()
    ):
        subset = successful.loc[
            successful["class"] == class_name
        ]

        iou = pd.to_numeric(
            subset["iou"],
            errors="coerce",
        ).dropna()

        dice = pd.to_numeric(
            subset["dice"],
            errors="coerce",
        ).dropna()

        gt_pixels = pd.to_numeric(
            subset["gt_pixels"],
            errors="coerce",
        ).dropna()

        prediction_pixels = pd.to_numeric(
            subset["prediction_pixels"],
            errors="coerce",
        ).dropna()

        prediction_gt_ratio = pd.to_numeric(
            subset["prediction_gt_ratio"],
            errors="coerce",
        ).dropna()

        gt_coverage = pd.to_numeric(
            subset["gt_coverage"],
            errors="coerce",
        ).dropna()

        row = {
            "class": class_name,
            "num_frames": int(len(subset)),
            "mean_iou": float(iou.mean()),
            "median_iou": float(iou.median()),
            "std_iou": float(iou.std(ddof=0)),
            "min_iou": float(iou.min()),
            "max_iou": float(iou.max()),
            "mean_dice": float(dice.mean()),
            "median_dice": float(dice.median()),
            "std_dice": float(dice.std(ddof=0)),
            "min_dice": float(dice.min()),
            "max_dice": float(dice.max()),
            "mean_gt_pixels": float(
                gt_pixels.mean()
            ),
            "mean_prediction_pixels": float(
                prediction_pixels.mean()
            ),
            "mean_prediction_gt_ratio": float(
                prediction_gt_ratio.mean()
            ),
            "mean_gt_coverage": float(
                gt_coverage.mean()
            ),
        }

        rows.append(row)

    return pd.DataFrame(rows)


# =============================================================================
# Plots
# =============================================================================

def plot_metric(
    frame: pd.DataFrame,
    class_name: str,
    metric: str,
    output_path: Path,
) -> None:
    """Plot one metric over selected frame numbers."""

    subset = frame.loc[
        (
            frame["class"] == class_name
        )
        & (
            frame["status"] == "ok"
        )
    ].copy()

    subset = subset.sort_values(
        "frame"
    )

    if subset.empty:
        return

    x = pd.to_numeric(
        subset["frame"],
        errors="coerce",
    )

    y = pd.to_numeric(
        subset[metric],
        errors="coerce",
    )

    fig = plt.figure(
        figsize=(10, 5)
    )

    axis = fig.add_subplot(111)

    axis.plot(
        x,
        y,
        marker="o",
    )

    axis.axhline(
        float(y.mean()),
        linestyle="--",
        label=f"Mean = {y.mean():.4f}",
    )

    axis.set_xlabel(
        "Video frame"
    )

    axis.set_ylabel(
        metric.upper()
    )

    axis.set_title(
        f"GX010129 - "
        f"{class_name.replace('_', ' ')} "
        f"{metric.upper()}"
    )

    axis.set_ylim(
        0.0,
        1.05,
    )

    axis.grid(
        True,
        alpha=0.3,
    )

    axis.legend()

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(fig)


def create_plots(
    frame: pd.DataFrame,
) -> None:
    """Generate IoU and Dice plots for both classes."""

    for class_name in CLASS_CONFIG:
        plot_metric(
            frame,
            class_name,
            "iou",
            OUTPUT_DIR
            / f"{class_name}_iou.png",
        )

        plot_metric(
            frame,
            class_name,
            "dice",
            OUTPUT_DIR
            / f"{class_name}_dice.png",
        )


