"""
evaluate_ground_truth_GX010129.py
=================================

Quantitative internal validation of the GX010129 segmentation results.

The script compares manually annotated binary ground-truth masks against
the corresponding binary masks generated by the video-processing pipeline.

Two semantic regions are evaluated independently:

    1. inner_pipe
    2. particle_bed

The existing repository functions

    src.evaluation.compute_iou()
    src.evaluation.compute_dice()

are reused for the actual segmentation metrics.

Input structure
---------------

data_gt/ground_truth/GX010129/
├── ground_truth/
│   ├── inner_pipe/
│   │   ├── frame_000000_inner_pipe_gt.png
│   │   └── ...
│   └── particle_bed/
│       ├── frame_000000_particle_bed_gt.png
│       └── ...
│
└── predictions/
    ├── inner_pipe/
    │   ├── frame_000000_inner_pipe.png
    │   └── ...
    └── particle_bed/
        ├── frame_000000_particle_bed.png
        └── ...

Output structure
----------------

results/internal_validation/GX010129/
├── per_frame_metrics.csv
├── summary_metrics.csv
├── validation_summary.txt
├── inner_pipe_iou.png
├── particle_bed_iou.png
├── inner_pipe_dice.png
└── particle_bed_dice.png

Author
------
Serge Kouomnankam
"""

