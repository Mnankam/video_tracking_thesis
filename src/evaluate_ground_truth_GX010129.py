GROUND_TRUTH_ROOT = ROOT / "ground_truth"
PREDICTION_ROOT = ROOT / "predictions"

GT_INNER_PIPE_DIR = GROUND_TRUTH_ROOT / "inner_pipe"
GT_PARTICLE_BED_DIR = GROUND_TRUTH_ROOT / "particle_bed"

PRED_INNER_PIPE_DIR = PREDICTION_ROOT / "inner_pipe"
PRED_PARTICLE_BED_DIR = PREDICTION_ROOT / "particle_bed"

OUTPUT_DIR = Path(
    "results/internal_validation/GX010129"
)

PER_FRAME_CSV = OUTPUT_DIR / "per_frame_metrics.csv"
SUMMARY_CSV = OUTPUT_DIR / "summary_metrics.csv"
SUMMARY_TXT = OUTPUT_DIR / "validation_summary.txt"

OVERLAY_DIR = OUTPUT_DIR / "overlays"


# =============================================================================
# Evaluated classes
# =============================================================================

CLASS_CONFIG = {
    "inner_pipe": {
        "gt_dir": GT_INNER_PIPE_DIR,
        "prediction_dir": PRED_INNER_PIPE_DIR,
        "gt_suffix": "_inner_pipe_gt.png",
        "prediction_suffix": "_inner_pipe.png",
    },
    "particle_bed": {
        "gt_dir": GT_PARTICLE_BED_DIR,
        "prediction_dir": PRED_PARTICLE_BED_DIR,
        "gt_suffix": "_particle_bed_gt.png",
        "prediction_suffix": "_particle_bed.png",
    },
}


# =============================================================================
# Utility functions
# =============================================================================

def ensure_output_directory() -> None:
    """Create all required output directories."""

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    OVERLAY_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


def validate_directories() -> None:
    """Validate all required input directories."""

    directories = [
        GT_INNER_PIPE_DIR,
        GT_PARTICLE_BED_DIR,
        PRED_INNER_PIPE_DIR,
        PRED_PARTICLE_BED_DIR,
    ]

    missing = [
        directory
        for directory in directories
        if not directory.is_dir()
    ]

    if missing:
        message = "\n".join(
            str(path)
            for path in missing
        )

        raise FileNotFoundError(
            "Required directories are missing:\n"
            f"{message}"
        )


def load_binary_mask(path: Path) -> np.ndarray:
    """
    Load a segmentation mask and convert it to a binary uint8 mask.

    Any non-zero pixel is interpreted as foreground.
    """

    mask = cv2.imread(
        str(path),
        cv2.IMREAD_GRAYSCALE,
    )

    if mask is None:
        raise RuntimeError(
            f"Mask could not be read:\n{path}"
        )

    binary = np.where(
        mask > 0,
        255,
        0,
    ).astype(np.uint8)

    return binary


def extract_frame_name(
    gt_path: Path,
    gt_suffix: str,
) -> str:
    """
    Extract the frame identifier from a ground-truth filename.

    Example:
        frame_015000_inner_pipe_gt.png
        -> frame_015000
    """

    filename = gt_path.name

    if not filename.endswith(gt_suffix):
        raise ValueError(
            f"Unexpected GT filename: {filename}"
        )

    return filename[:-len(gt_suffix)]


def frame_number_from_name(frame_name: str) -> int:
    """
    Convert 'frame_015000' to integer 15000.
    """

    prefix = "frame_"

    if not frame_name.startswith(prefix):
        raise ValueError(
            f"Unexpected frame name: {frame_name}"
        )

    return int(frame_name[len(prefix):])


def compute_pixel_statistics(
    gt_mask: np.ndarray,
    prediction_mask: np.ndarray,
) -> dict[str, float]:
    """
    Calculate foreground, intersection, union, ratio, and coverage values.
    """

    gt_bool = gt_mask.astype(bool)
    prediction_bool = prediction_mask.astype(bool)

    intersection = np.logical_and(
        gt_bool,
        prediction_bool,
    )

    union = np.logical_or(
        gt_bool,
        prediction_bool,
    )

    gt_pixels = int(
        np.count_nonzero(gt_bool)
    )

    prediction_pixels = int(
        np.count_nonzero(prediction_bool)
    )

    intersection_pixels = int(
        np.count_nonzero(intersection)
    )

    union_pixels = int(
        np.count_nonzero(union)
    )

    prediction_gt_ratio = (
        prediction_pixels / gt_pixels
        if gt_pixels > 0
        else np.nan
    )

    gt_coverage = (
        intersection_pixels / gt_pixels
        if gt_pixels > 0
        else np.nan
    )

    return {
        "gt_pixels": gt_pixels,
        "prediction_pixels": prediction_pixels,
        "intersection_pixels": intersection_pixels,
        "union_pixels": union_pixels,
        "prediction_gt_ratio": prediction_gt_ratio,
        "gt_coverage": gt_coverage,
    }


def save_segmentation_overlay(
    gt_mask: np.ndarray,
    prediction_mask: np.ndarray,
    output_path: Path,
) -> None:
    """
    Save a qualitative segmentation comparison.

    Colors:
        Green = true positive
        Red   = false negative
        Blue  = false positive
        Black = true negative
    """

    gt = gt_mask > 0
    prediction = prediction_mask > 0

    true_positive = np.logical_and(
        gt,
        prediction,
    )

    false_negative = np.logical_and(
        gt,
        np.logical_not(prediction),
    )

    false_positive = np.logical_and(
        np.logical_not(gt),
        prediction,
    )

    overlay = np.zeros(
        (
            gt.shape[0],
            gt.shape[1],
            3,
        ),
        dtype=np.uint8,
    )

    # OpenCV uses BGR channel order.
    overlay[true_positive] = (
        0,
        255,
        0,
    )

    overlay[false_negative] = (
        0,
        0,
        255,
    )

    overlay[false_positive] = (
        255,
        0,
        0,
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    success = cv2.imwrite(
        str(output_path),
        overlay,
    )

    if not success:
        raise RuntimeError(
            f"Could not write overlay image:\n"
            f"{output_path}"
        )


