# =============================================================================
# Directory handling
# =============================================================================

def create_directories() -> None:
    """Create all output directories required for annotation."""

    directories = [
        FRAME_OUTPUT_DIR,
        PARTICLE_BED_PREDICTION_OUTPUT_DIR,
        INNER_PIPE_PREDICTION_OUTPUT_DIR,
        PARTICLE_BED_GT_DIR,
        INNER_PIPE_GT_DIR,
    ]

    for directory in directories:
        directory.mkdir(
            parents=True,
            exist_ok=True,
        )


# =============================================================================
# File-name helpers
# =============================================================================

def frame_output_path(
    frame_number: int,
) -> Path:
    """Return output path of an extracted original video frame."""

    return (
        FRAME_OUTPUT_DIR
        / f"frame_{frame_number:06d}.png"
    )


def particle_bed_prediction_source_path(
    frame_number: int,
) -> Path:
    """Return original pipeline particle-bed mask path."""

    return (
        PARTICLE_BED_PREDICTION_DIR
        / f"frame_{frame_number:06d}_particle_bed.png"
    )


def particle_bed_prediction_output_path(
    frame_number: int,
) -> Path:
    """Return copied particle-bed prediction path."""

    return (
        PARTICLE_BED_PREDICTION_OUTPUT_DIR
        / f"frame_{frame_number:06d}_particle_bed.png"
    )


def inner_pipe_prediction_source_path(
    frame_number: int,
) -> Path:
    """Return original pipeline inner-pipe mask path."""

    return (
        INNER_PIPE_PREDICTION_DIR
        / f"frame_{frame_number:06d}_inner_pipe.png"
    )


def inner_pipe_prediction_output_path(
    frame_number: int,
) -> Path:
    """Return copied inner-pipe prediction path."""

    return (
        INNER_PIPE_PREDICTION_OUTPUT_DIR
        / f"frame_{frame_number:06d}_inner_pipe.png"
    )


def particle_bed_gt_path(
    frame_number: int,
) -> Path:
    """Return expected manual particle-bed ground-truth mask path."""

    return (
        PARTICLE_BED_GT_DIR
        / f"frame_{frame_number:06d}_particle_bed_gt.png"
    )


def inner_pipe_gt_path(
    frame_number: int,
) -> Path:
    """Return expected manual inner-pipe ground-truth mask path."""

    return (
        INNER_PIPE_GT_DIR
        / f"frame_{frame_number:06d}_inner_pipe_gt.png"
    )


# =============================================================================
# Input validation
# =============================================================================

def validate_inputs() -> None:
    """Check whether all required source data are available."""

    if not VIDEO_PATH.is_file():
        raise FileNotFoundError(
            "Video nicht gefunden:\n"
            f"{VIDEO_PATH}"
        )

    if not PARTICLE_BED_PREDICTION_DIR.is_dir():
        raise FileNotFoundError(
            "Particle-bed prediction directory not found:\n"
            f"{PARTICLE_BED_PREDICTION_DIR}"
        )

    if not INNER_PIPE_PREDICTION_DIR.is_dir():
        raise FileNotFoundError(
            "Inner-pipe prediction directory not found:\n"
            f"{INNER_PIPE_PREDICTION_DIR}"
        )


# =============================================================================
# Extraction
# =============================================================================

def extract_frames() -> list[dict]:
    """
    Extract selected original frames and copy matching prediction masks.

    Returns
    -------
    list[dict]
        Metadata for every selected frame.
    """

    cap = cv2.VideoCapture(
        str(VIDEO_PATH)
    )

    if not cap.isOpened():
        raise RuntimeError(
            "Video konnte nicht geöffnet werden:\n"
            f"{VIDEO_PATH}"
        )

    total_frames = int(
        cap.get(
            cv2.CAP_PROP_FRAME_COUNT
        )
    )

    fps = float(
        cap.get(
            cv2.CAP_PROP_FPS
        )
    )

    width = int(
        cap.get(
            cv2.CAP_PROP_FRAME_WIDTH
        )
    )

    height = int(
        cap.get(
            cv2.CAP_PROP_FRAME_HEIGHT
        )
    )

    print("=" * 80)
    print("GX010129 Ground-Truth Preparation")
    print("=" * 80)

    print(f"Video:                {VIDEO_PATH}")
    print(f"Video frames:         {total_frames}")
    print(f"FPS:                  {fps:.3f}")
    print(f"Resolution:           {width} x {height}")
    print(f"Selected frames:      {len(SELECTED_FRAMES)}")

    print()
    print("Objects:")
    print("  - particle_bed")
    print("  - inner_pipe")
    print()

    metadata: list[dict] = []

    for frame_number in SELECTED_FRAMES:

        # ---------------------------------------------------------------------
        # Validate requested frame number
        # ---------------------------------------------------------------------

        if (
            frame_number < 0
            or frame_number >= total_frames
        ):
            print(
                f"[WARNING] Frame {frame_number} is outside the "
                f"valid video range 0 ... {total_frames - 1}."
            )

            metadata.append(
                {
                    "frame": frame_number,
                    "time_seconds": "",
                    "frame_extracted": 0,
                    "particle_bed_prediction_found": 0,
                    "inner_pipe_prediction_found": 0,
                    "particle_bed_gt_created": 0,
                    "inner_pipe_gt_created": 0,
                }
            )

            continue

        # ---------------------------------------------------------------------
        # Extract original frame
        # ---------------------------------------------------------------------

        cap.set(
            cv2.CAP_PROP_POS_FRAMES,
            frame_number,
        )

        ok, frame = cap.read()

        if not ok:
            print(
                f"[ERROR] Frame {frame_number} could not be read."
            )

            metadata.append(
                {
                    "frame": frame_number,
                    "time_seconds": (
                        frame_number / fps
                        if fps > 0
                        else ""
                    ),
                    "frame_extracted": 0,
                    "particle_bed_prediction_found": 0,
                    "inner_pipe_prediction_found": 0,
                    "particle_bed_gt_created": 0,
                    "inner_pipe_gt_created": 0,
                }
            )

            continue

        output_frame_path = (
            frame_output_path(
                frame_number
            )
        )

        saved = cv2.imwrite(
            str(output_frame_path),
            frame,
        )

        if not saved:
            raise RuntimeError(
                "Frame could not be saved:\n"
                f"{output_frame_path}"
            )

        # ---------------------------------------------------------------------
        # Particle-bed prediction
        # ---------------------------------------------------------------------

        particle_source = (
            particle_bed_prediction_source_path(
                frame_number
            )
        )

        particle_found = (
            particle_source.is_file()
        )

        if particle_found:
            shutil.copy2(
                particle_source,
                particle_bed_prediction_output_path(
                    frame_number
                ),
            )

        # ---------------------------------------------------------------------
        # Inner-pipe prediction
        # ---------------------------------------------------------------------

        pipe_source = (
            inner_pipe_prediction_source_path(
                frame_number
            )
        )

        pipe_found = (
            pipe_source.is_file()
        )

        if pipe_found:
            shutil.copy2(
                pipe_source,
                inner_pipe_prediction_output_path(
                    frame_number
                ),
            )

        # ---------------------------------------------------------------------
        # Ground-truth status
        # ---------------------------------------------------------------------

        particle_gt_exists = (
            particle_bed_gt_path(
                frame_number
            ).is_file()
        )

        pipe_gt_exists = (
            inner_pipe_gt_path(
                frame_number
            ).is_file()
        )

        # ---------------------------------------------------------------------
        # Time
        # ---------------------------------------------------------------------

        time_seconds = (
            frame_number / fps
            if fps > 0
            else float("nan")
        )

        # ---------------------------------------------------------------------
        # Console output
        # ---------------------------------------------------------------------

        print(
            f"Frame {frame_number:6d} | "
            f"t={time_seconds:8.3f} s | "
            f"bed={'OK' if particle_found else 'MISSING':7s} | "
            f"pipe={'OK' if pipe_found else 'MISSING':7s}"
        )

        # ---------------------------------------------------------------------
        # Manifest row
        # ---------------------------------------------------------------------

        metadata.append(
            {
                "frame": frame_number,
                "time_seconds": time_seconds,
                "frame_extracted": 1,
                "particle_bed_prediction_found": (
                    1 if particle_found else 0
                ),
                "inner_pipe_prediction_found": (
                    1 if pipe_found else 0
                ),
                "particle_bed_gt_created": (
                    1 if particle_gt_exists else 0
                ),
                "inner_pipe_gt_created": (
                    1 if pipe_gt_exists else 0
                ),
            }
        )

    cap.release()

    return metadata


# =============================================================================
# Manifest
# =============================================================================

def save_manifest(
    metadata: list[dict],
) -> None:
    """Write information about all selected frames to CSV."""

    fieldnames = [
        "frame",
        "time_seconds",
        "frame_extracted",
        "particle_bed_prediction_found",
        "inner_pipe_prediction_found",
        "particle_bed_gt_created",
        "inner_pipe_gt_created",
    ]

    with MANIFEST_CSV.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        writer.writerows(
            metadata
        )


