"""
extract_ground_truth_frames_GX010129.py
=======================================

Prepare representative frames from GX010129.MP4 for manual
ground-truth annotation of

    1. particle bed
    2. inner pipe

The script extracts selected original video frames and copies the
corresponding binary prediction masks already generated by the pipeline.

Output structure
----------------

data/ground_truth/GX010129/
├── frames/
│   ├── frame_000000.png
│   ├── frame_001500.png
│   └── ...
│
├── predictions/
│   ├── particle_bed/
│   │   ├── frame_000000_particle_bed.png
│   │   └── ...
│   │
│   └── inner_pipe/
│       ├── frame_000000_inner_pipe.png
│       └── ...
│
├── ground_truth/
│   ├── particle_bed/
│   │   ├── frame_000000_particle_bed_gt.png
│   │   └── ...
│   │
│   └── inner_pipe/
│       ├── frame_000000_inner_pipe_gt.png
│       └── ...
│
└── selected_frames.csv

The ground-truth directories are initially empty. The masks must be
created manually after the selected original frames have been inspected.

Mask convention
---------------

0   = background
255 = object

Author
------
Serge Kouomnankam
"""

